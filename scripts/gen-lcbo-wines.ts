/**
 * Builds app/alcohol/lib/lcboWinesData.ts from crawled LCBO product-page records.
 *
 * Input: one or more JSONL files, one record per LCBO product page (see
 * scripts/crawl-lcbo-products.cjs). Wine only: breadcrumb "Wine > Red/White/Rosé/
 * Sparkling/Champagne/Icewine/Dessert". Fortified, specialty, gift and multi-pack
 * entries are skipped. Nothing is invented: a wine without a published ABV or
 * sugar figure is stored with those fields blank and shows "Score pending".
 *
 * Usage: npx tsx scripts/gen-lcbo-wines.ts <file1.jsonl> [file2.jsonl ...]
 */
import fs from "fs";
import path from "path";

type Rec = {
  u: string; num?: string; name?: string; cats?: string[]; size?: string; abv?: number; sugarGL?: number;
  madeIn?: string; appellation?: string; by?: string; style?: string; varietal?: string; status?: number; error?: string;
};

const SUB: Record<string, string> = {
  "Red Wine": "R", "White Wine": "W", "Rosé Wine": "P", "Rose Wine": "P", "Rosé": "P",
  "Sparkling Wine": "S", "Champagne": "S", "Icewine": "I", "Dessert Wine": "D",
};

/** Bottle size in mL, or 0 when the LCBO page did not give one (never guessed). */
function sizeMl(s?: string): number {
  if (!s) return 0;
  const m = s.match(/^(\d[\d.,]*)\s*(mL|ml|L)/);
  if (!m) return 0;
  const n = parseFloat(m[1].replace(",", "."));
  return Math.round(m[2] === "L" ? n * 1000 : n);
}

const PREFIX = /^(château|chateau|domaine|bodegas|bodega|casa|cantina|tenuta|villa|maison|weingut|cave|clos|castello|cellar|cellars|quinta|herdade|finca|marqués|marques|dr\.?|don|conde|famille|mas|dominio)$/i;
const PROGRAM = /vintages|release|collection|selection|classics|essentials|private|reserve list/i;
/** LCBO's "By" field is sometimes a program ("Vintages Front Line Release"), not a producer. */
function brandFor(by: string | undefined, name: string): string {
  // "By" is sometimes a distributor/agency ("Magstar Directs (Non Cc)"); trust it only when the product name carries it.
  const fold = (x: string) => x.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
  if (by && !PROGRAM.test(by) && fold(name).includes(fold(by).split(/\s+/)[0])) return by;
  const w = name.split(/\s+/);
  return PREFIX.test(w[0] ?? "") && w[1] ? `${w[0]} ${w[1]}` : (w[0] ?? "");
}

const files = process.argv.slice(2);
if (!files.length) { console.error("pass crawl .jsonl files"); process.exit(1); }

const byNum = new Map<string, Rec>();
for (const f of files) {
  for (const line of fs.readFileSync(f, "utf8").split(/\r?\n/)) {
    if (!line) continue;
    let r: Rec;
    try { r = JSON.parse(line); } catch { continue; }
    if (!r.num || !r.name || !r.cats || r.cats[0] !== "Wine") continue;
    byNum.set(r.num, r);
  }
}

const rows: unknown[][] = [];
let skippedSub = 0, skippedPack = 0, noAbv = 0, noSugar = 0;
for (const r of byNum.values()) {
  const sub = SUB[r.cats![1] ?? ""];
  if (!sub) { skippedSub++; continue; }
  if (/\b(gift|packs?|box of|sampler|mixed)\b|\(case\)|\bcase of\b|\bset of\b/i.test(r.name!)) { skippedPack++; continue; }
  const ml = sizeMl(r.size);
  if (ml > 0 && ml < 187) { skippedPack++; continue; }
  const vqa = /VQA/i.test(`${r.appellation ?? ""} ${r.name}`);
  const name = r.name!.replace(/\s+(VQA|DOCG|DOC|AOC|AOP|IGT|IGP)\b/gi, "").replace(/\s+/g, " ").trim();
  const region = [r.appellation && !/^VQA$/i.test(r.appellation) ? r.appellation : undefined, r.madeIn, vqa ? "VQA" : undefined].filter(Boolean).join(", ");
  if (r.abv === undefined || Number.isNaN(r.abv)) noAbv++;
  if (r.sugarGL === undefined || Number.isNaN(r.sugarGL)) noSugar++;
  rows.push([
    r.num, brandFor(r.by, name), name, sub,
    r.abv !== undefined && !Number.isNaN(r.abv) ? r.abv : 0,
    r.sugarGL !== undefined && !Number.isNaN(r.sugarGL) ? r.sugarGL : -1,
    ml, region, r.varietal ?? "", vqa ? 1 : 0,
  ]);
}
rows.sort((a, b) => String(a[1]).localeCompare(String(b[1])) || String(a[2]).localeCompare(String(b[2])));

const out = path.resolve("app/alcohol/lib/lcboWinesData.ts");
const header = `/**
 * LCBO wine catalogue — GENERATED by scripts/gen-lcbo-wines.ts from lcbo.com product pages
 * (ABV and residual sugar are the LCBO's own published figures). Server-side only:
 * imported by lcboWines.server.ts and served through /api/wines, never bundled into client JS.
 * Tuple: [lcboNumber, brand, name, sub (R/W/P/S/I/D), abv (0 = unpublished),
 *         sugarGPerL (-1 = unpublished), bottleSizeMl, region, varietal, vqa(0/1)]
 */
export type LcboWineRow = readonly [string, string, string, string, number, number, number, string, string, number];
export const LCBO_WINES: readonly LcboWineRow[] = `;
fs.writeFileSync(out, header + JSON.stringify(rows).replace(/\],\[/g, "],\n[") + " as const;\n");
console.log(`wines written ${rows.length} | skipped non-table ${skippedSub} | packs/small ${skippedPack} | no ABV ${noAbv} | no sugar ${noSugar}`);
