/**
 * Builds app/alcohol/lib/magnottaData.ts from magnotta.com product pages. Each page publishes
 * "Alcohol" (%) and "Sugar Content" (g/L); wines without both stay "Score pending". Gift sets,
 * crates, brandy and liqueur products are skipped.
 * Usage: npx tsx scripts/gen-magnotta.ts <magnotta.jsonl>
 */
import fs from "fs";
import path from "path";

type Rec = { u: string; id?: string; cat?: string; name?: string; size?: string; abv?: string; sugar?: string; error?: string };
const file = process.argv[2];
if (!file) { console.error("usage: gen-magnotta.ts <magnotta.jsonl>"); process.exit(1); }

const SUB: Record<string, string> = { Red: "R", White: "W", Rose: "P", Sparkling: "S", Icewine: "I", Dessert: "D", Speciality: "D" };
const rows: unknown[][] = [];
let skipped = 0;
for (const l of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
  if (!l) continue;
  const r: Rec = JSON.parse(l);
  if (r.error || !r.name || !r.id) { skipped++; continue; }
  let name = r.name.replace(/ONLINE EXCLUSIVE/gi, "").replace(/\d{4}\s+DOUBLE GOLD Winner:\s*/i, "").replace(/\s+/g, " ").trim();
  if (/gift|crate|brandy|liqueur|set\b/i.test(name)) { skipped++; continue; }
  const vqa = /VQA/i.test(name) ? 1 : 0;
  name = name.replace(/\s+VQA\b/gi, "").replace(/\s+Niagara Peninsula\b/i, "").replace(/\s+Limited Edition\b/i, "");
  const m = (r.size ?? "").match(/(\d+(?:\.\d+)?)\s*(mL|L)/i);
  const ml = m ? Math.round(/^l$/i.test(m[2]) ? parseFloat(m[1]) * 1000 : parseFloat(m[1])) : 0;
  rows.push([
    r.id, "Magnotta", name, SUB[r.cat ?? ""] ?? "R",
    r.abv ? parseFloat(r.abv) : 0, r.sugar ? parseFloat(r.sugar) : -1, ml,
    vqa ? "Ontario VQA, Canada" : "Ontario, Canada", "", vqa,
  ]);
}
rows.sort((a, b) => String(a[2]).localeCompare(String(b[2])));
const out = path.resolve("app/alcohol/lib/magnottaData.ts");
const header = `/**
 * Magnotta Winery catalogue (magnotta.com product pages: alcohol %, sugar g/L) — GENERATED by scripts/gen-magnotta.ts.
 * Server-side only, like lcboWinesData.ts. Tuple: [productId, brand, name, sub (R/W/P/S/I/D),
 *   abv (0 = unpublished), sugarGPerL (-1 = unpublished), bottleSizeMl (0 = unknown), region, varietal, vqa(0/1)]
 */
export type MagnottaRow = readonly [string, string, string, string, number, number, number, string, string, number];
export const MAGNOTTA: readonly MagnottaRow[] = `;
fs.writeFileSync(out, header + JSON.stringify(rows).replace(/\],\[/g, "],\n[") + " as const;\n");
console.log(`magnotta wines written ${rows.length} | skipped ${skipped}`);
