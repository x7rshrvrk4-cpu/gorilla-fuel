/**
 * Builds app/alcohol/lib/wineRackData.ts from The Wine Rack's own product pages (winerack.com).
 * Each product page publishes "Technical Notes": alcohol %, residual sugar (g/L), varietal and region,
 * the same facts we use to score LCBO wines. Nothing is invented: a wine without a published ABV or
 * residual sugar keeps those fields blank and shows "Score pending".
 *
 * Input: JSONL of crawled product records plus a categories map (see the crawl notes in the commit).
 * Usage: npx tsx scripts/gen-wine-rack.ts <products.jsonl> <categories.json>
 */
import fs from "fs";
import path from "path";

type Rec = {
  u: string; id?: string; name?: string | null; size?: string; abv?: string; sugar?: string; varietal?: string;
  designation?: string; country?: string; region?: string; appellation?: string; error?: string;
};

const [, , productsFile, categoriesFile] = process.argv;
if (!productsFile || !categoriesFile) { console.error("usage: gen-wine-rack.ts <products.jsonl> <categories.json>"); process.exit(1); }

const BRANDS = ["Blake Boulevard", "Jackson-Triggs", "Inniskillin", "Sandbanks", "Sawmill Creek", "Kew Vineyards", "Maria Christina", "Vintage Ink", "Wallaroo Trail", "Good Fortune", "Sola Nero", "Bodacious", "Saintly", "Svelte", "Ziraldo", "Caleta", "Mazia", "Sidney", "BASK", "Bù", "Bu", "Open", "MXM"];
const cats: Record<string, string[]> = JSON.parse(fs.readFileSync(categoriesFile, "utf8"));
const byUrl = new Map<string, Rec>();
for (const l of fs.readFileSync(productsFile, "utf8").split(/\r?\n/)) {
  if (!l) continue;
  try { const r: Rec = JSON.parse(l); if (!r.error) byUrl.set(r.u, r); } catch {}
}

function sizeMl(s?: string): number {
  const m = (s ?? "").match(/^(\d[\d.]*)\s*(ml|L)/i);
  if (!m) return 0;
  const n = parseFloat(m[1]);
  return Math.round(/l/i.test(m[2]) && !/ml/i.test(m[2]) ? n * 1000 : n);
}
const num = (s?: string): number | undefined => {
  const m = (s ?? "").match(/[\d.]+/);
  return m ? parseFloat(m[0]) : undefined;
};

const rows: unknown[][] = [];
let skipped = 0, noAbv = 0, noSugar = 0;
for (const r of byUrl.values()) {
  if (!r.name || !r.id) { skipped++; continue; }
  const name = r.name.replace(/\s+/g, " ").trim();
  if (/hard sparkling water|irish cream|s'mores|salted caramel|cream\b/i.test(name)) { skipped++; continue; } // not wine
  const c = cats[r.id] ?? [];
  let sub = "R";
  if (c.includes("wine-white")) sub = "W";
  else if (c.includes("wine-rose")) sub = "P";
  else if (c.includes("wine-flavoured") || c.includes("wine-other")) sub = "D";
  if (/icewine/i.test(name) && !/sparkling/i.test(name)) sub = "I";
  else if (/sparkling/i.test(name)) sub = "S";
  const brand = BRANDS.find((b) => name.toLowerCase().startsWith(b.toLowerCase())) ?? name.split(" ")[0];
  const abv = num(r.abv);
  const sugar = r.sugar ? num(r.sugar) : undefined;
  if (abv === undefined) noAbv++;
  if (sugar === undefined) noSugar++;
  const vqa = /VQA/i.test(`${r.designation ?? ""} ${name}`) ? 1 : 0;
  const region = [r.appellation && r.appellation !== "Ontario" ? r.appellation : undefined, r.region ? r.region[0] + r.region.slice(1).toLowerCase() : undefined, r.country].filter(Boolean).join(", ");
  rows.push([r.id, brand, name.replace(/\s+VQA$/i, ""), sub, abv ?? 0, sugar ?? -1, sizeMl(r.size), region, (r.varietal ?? "").replace(/^N\/A$/i, ""), vqa]);
}
rows.sort((a, b) => String(a[1]).localeCompare(String(b[1])) || String(a[2]).localeCompare(String(b[2])));

const out = path.resolve("app/alcohol/lib/wineRackData.ts");
const header = `/**
 * The Wine Rack catalogue (Ontario winery boutiques inside grocery stores) — GENERATED by scripts/gen-wine-rack.ts
 * from winerack.com product pages ("Technical Notes": alcohol %, residual sugar g/L, varietal, region).
 * Server-side only, like lcboWinesData.ts. Tuple: [productId, brand, name, sub (R/W/P/S/I/D),
 *   abv (0 = unpublished), sugarGPerL (-1 = unpublished), bottleSizeMl (0 = unknown), region, varietal, vqa(0/1)]
 */
export type WineRackRow = readonly [string, string, string, string, number, number, number, string, string, number];
export const WINE_RACK: readonly WineRackRow[] = `;
fs.writeFileSync(out, header + JSON.stringify(rows).replace(/\],\[/g, "],\n[") + " as const;\n");
console.log(`wines written ${rows.length} | skipped ${skipped} (not wine / no name) | no ABV ${noAbv} | no sugar ${noSugar}`);
